package dev.pocketagent.runtime

/** Shell startup shared by normal and elevated interactive terminals. No UID is changed here. */
internal object UnifiedTerminalShell {
    fun quote(value: String): String = "'" + value.replace("'", "'\"'\"'") + "'"

    fun rootCommand(environment: Array<String>, bash: String, cwd: String, command: String): String {
        val exports = environment.filterNot {
            it.startsWith("LD_PRELOAD=") || it.startsWith("TERMUX_EXEC__")
        }.joinToString("\n") { "export ${quote(it)}" }
        return "unset LD_PRELOAD LD_LIBRARY_PATH;\n$exports\n" +
            "cd -- ${quote(cwd)} || exit; exec ${quote(bash)} --noprofile --norc -c ${quote(command)}"
    }

    fun rc(environment: Array<String>, bash: String, rcPath: String, suPath: String?): String {
        val rootEnvironment = environment.filterNot {
            it.startsWith("LD_PRELOAD=") || it.startsWith("TERMUX_EXEC__")
        }
        val exports = rootEnvironment.joinToString("\n") { "export ${quote(it)}" }
        val rootLaunch = "unset LD_PRELOAD LD_LIBRARY_PATH;\n$exports\n" +
            "cd -- \"\$1\" || exit; exec ${quote(bash)} --noprofile --rcfile ${quote(rcPath)} -i"
        val su = suPath?.let(::quote)
        return """
            # Generated by CodeMate; user customizations belong in ~/.bashrc.
            if [ -r "${'$'}HOME/.bashrc" ]; then . "${'$'}HOME/.bashrc"; fi
            if [ "${'$'}EUID" -eq 0 ]; then
                export HISTFILE="${'$'}HOME/.bash_history_root"
                PS1='\u@codemate:\w# '
            else
                PS1='\u@codemate:\w\${'$'} '
            fi
            su() {
                ${if (su == null) "printf '没有找到可用的 su\\n' >&2; return 127" else """
                if [ "${'$'}#" -eq 0 ]; then
                    local root_command
                    printf -v root_command '%s %q' ${quote("/system/bin/sh -c ${quote(rootLaunch)} codemate-root")} "${'$'}PWD"
                    (unset LD_PRELOAD LD_LIBRARY_PATH; $su -c "${'$'}root_command")
                else
                    # Preserve native su options, e.g. su -c, rather than interpreting them.
                    (unset LD_PRELOAD LD_LIBRARY_PATH; $su "${'$'}@")
                fi
                """.trimIndent()}
            }
        """.trimIndent() + "\n"
    }
}
